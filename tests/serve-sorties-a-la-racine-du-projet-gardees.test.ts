// `mjs serve` (le serveur de production) avec `"outputDir": "."` : le dossier servi est la racine du projet, et tout ce qui s'y trouve
// partait — `mjs.config.json` (jeton de la visionneuse compris), `secrets.json`, `config/*.yml`, les entrées serveur, le journal
// `log/…`. Même garde que `mjs dev` (une seule aide pour les deux serveurs) ; les sorties que le build écrit lui-même (liste de
// pré-cache, fichiers de messages, cœur, fragments de traduction, feuilles marquées) restent servies

import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { mjsTmp } from './helpers/tmp.js'
import { startRenderServer } from '../src/server/render-server.js'
import { terminateSharedWorkerPool } from '../src/bundler/index.js'
import { shortFingerprint } from '../src/bundler/fingerprint.js'

describe('mjs serve — dossier de sortie à la racine du projet', function () {
  after(async () => { await terminateSharedWorkerPool() })

  it('les fichiers privés du projet ne sortent pas, les sorties du build si', async function () {
    this.timeout(60000)
    const root   = mjsTmp('serve-racine')
    const ecrire = (p: string, s: string): void => { mkdirSync(dirname(join(root, p)), { recursive: true }); writeFileSync(join(root, p), s) }
    const config: any = { sourceDir: 'app/modularjs', outputDir: '.', journal: { viewer: 'JETON-SECRET-123' }, ws: { entry: 'temps-reel/point.js' }, render: { routes: { '/page': { component: 'mjs-page', mode: 'csr' } } } }
    ecrire('mjs.config.json', JSON.stringify(config))
    ecrire('app/modularjs/page.mjs', '<p>page</p>\n')
    const prives = ['secrets.json', 'config/database.yml', 'server.mjs', 'ws.js', 'log/mjs-errors-server.ndjson', 'package.json', 'Gemfile', 'server/db.js', 'temps-reel/point.js']
    for (const p of prives) ecrire(p, 'SECRET ' + p)
    const coeur    = '/* cœur */'
    const messages = '{"m":"message"}'
    const sorties: Record<string, string> = {
      'mjs-precache.json': '{"version":"a1b2c3d4","assets":["/mjs_core.js"]}',
      ['mjs_core-' + shortFingerprint(coeur) + '.js']: coeur,
      ['mjs_err-fr-' + shortFingerprint(messages) + '.json']: messages,
      'i18n/fr/accueil.json': '{"titre":"Accueil"}',
      'carte.large.css': '/* @generated by ModularJS */\n.carte{}',
      'carte.server.css': '/* @generated by ModularJS */\n.carte{}',
    }
    for (const [p, s] of Object.entries(sorties)) ecrire(p, s)
    const serveur = await startRenderServer(config, root, { port: 0, host: '127.0.0.1', env: 'prod' })
    try {
      for (const p of ['mjs.config.json', 'app/modularjs/page.mjs', ...prives]) {
        const r     = await fetch(`http://127.0.0.1:${serveur.port}/${p}`)
        const corps = await r.text()
        assert.ok(!/SECRET|JETON/.test(corps), `/${p} servi (${r.status})`)
      }
      for (const [p, s] of Object.entries(sorties)) {
        const r = await fetch(`http://127.0.0.1:${serveur.port}/${p}`)
        assert.equal(r.status, 200, '/' + p)
        assert.equal(await r.text(), s, '/' + p)
      }
    } finally {
      await serveur.close()
    }
  })
})
